#!/usr/bin/env node
// Deploys the site as a public Supabase Edge Function ("site") on the
// association's FAEMSE WEBSITE project, serving the static build.
//
// Usage:  SUPABASE_ACCESS_TOKEN=sbp_... node scripts/deploy-supabase.mjs
//
// The site is served at:
//   https://iybsnqcffrhzhdpyoaqt.supabase.co/functions/v1/site/
//
// This is the interim public URL until DNS cutover to faemse.org on a
// static host (see README "Deploying / migrating").

import { execSync } from 'node:child_process';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const PROJECT_REF = 'iybsnqcffrhzhdpyoaqt';
const SLUG = 'site';
const BASE_PATH = `/functions/v1/${SLUG}/`;

// --generate-only writes the function source to supabase/functions/site/index.ts
// without deploying (deploy it yourself via the management API or supabase CLI).
const generateOnly = process.argv.includes('--generate-only');
const token = process.env.SUPABASE_ACCESS_TOKEN;
if (!token && !generateOnly) {
  console.error('Set SUPABASE_ACCESS_TOKEN (a sbp_... personal access token).');
  process.exit(1);
}

console.log(`Building with BASE_PATH=${BASE_PATH} ...`);
execSync('npx vite build', {
  stdio: 'inherit',
  env: { ...process.env, BASE_PATH },
});

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.webp': 'image/webp',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
  '.woff': 'font/woff',
  '.json': 'application/json',
  '.txt': 'text/plain; charset=utf-8',
  '.xml': 'application/xml',
  '.webmanifest': 'application/manifest+json',
};

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

// The Supabase functions gateway rewrites text/html responses to text/plain
// on the shared *.supabase.co domain (anti-phishing). Browsers render
// application/xhtml+xml identically, and the gateway leaves it alone — so the
// HTML shell is converted to well-formed XHTML and served as XHTML.
function toXhtml(html) {
  // Chromium doesn't run module scripts in XML documents (crbug.com/717643);
  // the single-chunk Vite bundle has no import/export, so load it as a classic
  // script — and since defer is ignored in XML docs, at the end of <body>.
  const src = /<script type="module"[^>]*\ssrc="([^"]*)"><\/script>/.exec(html)?.[1];
  if (!src) throw new Error('module script tag not found in index.html');
  return html
    .replace(/^<!doctype html>/i, '<!DOCTYPE html>')
    .replace('<html lang="en">', '<html lang="en" xmlns="http://www.w3.org/1999/xhtml">')
    .replace(/\scrossorigin(?=[\s>])/g, ' crossorigin="anonymous"')
    .replace(/<(meta|link)([^>]*?)\s*\/?>/g, '<$1$2 />')
    .replace(/<script type="module"[^>]*\ssrc="[^"]*"><\/script>\s*/, '')
    .replace(/<\/body>/, `  <script src="${src}"></script>\n  </body>`);
}

const files = {};
for (const p of walk('dist')) {
  const rel = '/' + relative('dist', p).replaceAll('\\', '/');
  const isHtml = extname(rel) === '.html';
  files[rel] = {
    t: isHtml ? 'application/xhtml+xml; charset=utf-8' : (MIME[extname(rel)] ?? 'application/octet-stream'),
    d: (isHtml
      ? Buffer.from(toXhtml(readFileSync(p, 'utf8')), 'utf8')
      : readFileSync(p)
    ).toString('base64'),
  };
}
console.log(`Embedding ${Object.keys(files).length} files from dist/`);

const source = `// Auto-generated by scripts/deploy-supabase.mjs — do not edit.
// Serves the FAEMSE website build as static files with an SPA fallback.
const FILES: Record<string, { t: string; d: string }> = ${JSON.stringify(files)};

function body(f: { d: string }): Uint8Array {
  return Uint8Array.from(atob(f.d), (c) => c.charCodeAt(0));
}

Deno.serve((req: Request) => {
  let path = new URL(req.url).pathname;
  path = path.replace(/^\\/functions\\/v1/, '').replace(/^\\/${SLUG}/, '');
  if (path === '' || path === '/') path = '/index.html';
  const hit = FILES[path];
  const f = hit ?? FILES['/index.html'];
  const headers = new Headers({ 'content-type': f.t });
  headers.set(
    'cache-control',
    hit && path.startsWith('/assets/')
      ? 'public, max-age=31536000, immutable'
      : 'no-cache',
  );
  return new Response(body(f), { status: 200, headers });
});
`;

if (generateOnly) {
  const { mkdirSync, writeFileSync } = await import('node:fs');
  mkdirSync('supabase/functions/site', { recursive: true });
  writeFileSync('supabase/functions/site/index.ts', source);
  console.log('Wrote supabase/functions/site/index.ts');
  process.exit(0);
}

console.log('Deploying edge function ...');
const form = new FormData();
form.append(
  'metadata',
  JSON.stringify({
    name: SLUG,
    entrypoint_path: 'index.ts',
    verify_jwt: false,
  }),
);
form.append('file', new Blob([source], { type: 'application/typescript' }), 'index.ts');

const res = await fetch(
  `https://api.supabase.com/v1/projects/${PROJECT_REF}/functions/deploy?slug=${SLUG}`,
  { method: 'POST', headers: { authorization: `Bearer ${token}` }, body: form },
);
const out = await res.text();
if (!res.ok) {
  console.error(`Deploy failed (${res.status}): ${out}`);
  process.exit(1);
}
console.log(`Deployed: https://${PROJECT_REF}.supabase.co${BASE_PATH}`);
